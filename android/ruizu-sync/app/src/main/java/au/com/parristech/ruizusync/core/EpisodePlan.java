package au.com.parristech.ruizusync.core;

import java.io.IOException;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collection;
import java.util.Collections;
import java.util.Comparator;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.function.BooleanSupplier;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Episode identity, naming, planning and reconciliation rules shared with the Termux
 * pipeline ({@code tools/ruizu-episode-pipeline}, modules {@code names.py} and {@code planner.py}).
 *
 * <p>Pure Java so the rules are covered by the JVM gate. The two implementations must agree:
 * {@code EpisodePlanTest} pins labels generated by the Python implementation, because both
 * players already hold episodes named {@code <Show SxxEyy> - RUIZU.amv} and a different name
 * would make the native queue copy every episode a second time.
 *
 * <p>Deliberate difference: source names here come from SAF display names, not HTML, so only
 * tags and the common character entities are decoded (the Python side decodes all HTML entities).
 */
public final class EpisodePlan {
    private EpisodePlan() {}

    public static final String PLAYER_SUFFIX = " - RUIZU.amv";
    public static final int MAX_LABEL = 120;

    public static final Pattern VIDEO_EXT = Pattern.compile("\\.(avi|mp4|mkv|mov|m4v|webm|mpg|mpeg)$", Pattern.CASE_INSENSITIVE);
    private static final Pattern SXXEYY = Pattern.compile("(?:^|[^A-Za-z0-9])[Ss](\\d{1,2})[ ._-]?[Ee](\\d{1,3})(?:[^0-9]|$)");
    private static final Pattern NXNN = Pattern.compile("(?:^|[^0-9])(\\d{1,2})x(\\d{1,3})(?:[^0-9]|$)");
    private static final Pattern SEASON_FOLDER = Pattern.compile("season\\s*(\\d{1,2})", Pattern.CASE_INSENSITIVE);
    private static final Pattern SEASON_TOKEN = Pattern.compile("(?:^|[^A-Za-z0-9])(?:[Ss](\\d{1,2})|(\\d{1,2})x[Ee][Xx])(?:[^0-9]|$)");
    private static final Pattern NOISE = Pattern.compile(
        "\\b(\\d{1,2}x[Ee][Xx]|[Ss]\\d{1,2}|x26[45]|h\\.?26[45]|hevc|xvid|divx|\\d{3,4}p|"
            + "web-?dl|webrip|hdtv|bluray|brrip|dvdrip|aac|ac3|dd5\\.1)\\b", Pattern.CASE_INSENSITIVE);
    private static final Pattern TAG = Pattern.compile("<[^>]+>");
    private static final Pattern UNSAFE = Pattern.compile("[\\x00-\\x1f\\x7f/\\\\:*?\"<>|]+");
    // Explicit Unicode whitespace (as Python's \s): Android's regex engine does not support UNICODE_CHARACTER_CLASS.
    private static final Pattern SPACES = Pattern.compile("[\\s\\u00A0\\u1680\\u2000-\\u200A\\u2028\\u2029\\u202F\\u205F\\u3000]+");
    private static final Pattern LABEL_NUMBERED = Pattern.compile("(.*?) S(\\d{1,2})E(\\d{1,3})");
    private static final Pattern LABEL_EXTRA = Pattern.compile("(.*?) S(\\d{1,2}) - .+");

    // ---- identity and names ----------------------------------------------------------

    public enum Kind { EPISODE, EXTRA, DUPLICATE }

    /** What a video file is: a numbered episode, or an extra with at most a season. */
    public static final class Identity {
        public final Kind kind;
        public final Integer season;
        public final Integer episode;
        public final String label;

        Identity(Kind kind, Integer season, Integer episode, String label) {
            this.kind = kind;
            this.season = season;
            this.episode = episode;
            this.label = label;
        }
    }

    /** Safe text for a FAT file name from an untrusted name. */
    public static String cleanText(String raw) {
        return cleanText(raw, MAX_LABEL);
    }

    static String cleanText(String raw, int limit) {
        String text = decodeEntities(TAG.matcher(raw == null ? "" : raw).replaceAll(""));
        text = strip(SPACES.matcher(UNSAFE.matcher(text).replaceAll(" ")).replaceAll(" "), " .");
        return stripTrailing(text.length() > limit ? text.substring(0, limit) : text, " .");
    }

    private static String decodeEntities(String text) {
        return text.replace("&lt;", "<").replace("&gt;", ">").replace("&quot;", "\"")
            .replace("&#39;", "'").replace("&#x27;", "'").replace("&amp;", "&");
    }

    private static String strip(String text, String chars) {
        int start = 0;
        while (start < text.length() && chars.indexOf(text.charAt(start)) >= 0) start++;
        return stripTrailing(text.substring(start), chars);
    }

    private static String stripTrailing(String text, String chars) {
        int end = text.length();
        while (end > 0 && chars.indexOf(text.charAt(end - 1)) >= 0) end--;
        return text.substring(0, end);
    }

    /** Season and episode from a file name ("S02E11", "s4 e12" or "3x07"), else null. */
    public static int[] episodeNumbers(String filename) {
        for (Pattern pattern : Arrays.asList(SXXEYY, NXNN)) {
            Matcher m = pattern.matcher(filename);
            if (m.find()) return new int[] {Integer.parseInt(m.group(1)), Integer.parseInt(m.group(2))};
        }
        return null;
    }

    /** Season of an un-numbered extra, from a "Season N" folder or an S05 / 6xEX token. */
    static Integer seasonHint(String path) {
        String[] parts = path.split("/", -1);
        for (int i = parts.length - 2; i >= 0; i--) {
            Matcher folder = SEASON_FOLDER.matcher(parts[i]);
            if (folder.find()) return Integer.parseInt(folder.group(1));
        }
        Matcher token = SEASON_TOKEN.matcher(parts[parts.length - 1]);
        if (!token.find()) return null;
        return Integer.parseInt(token.group(1) != null ? token.group(1) : token.group(2));
    }

    static String extraTitle(String show, String filename) {
        String words = VIDEO_EXT.matcher(filename).replaceAll("").replaceAll("[._]+", " ");
        words = Pattern.compile("^\\s*" + Pattern.quote(show) + "\\b", Pattern.CASE_INSENSITIVE)
            .matcher(words).replaceAll("");
        String title = cleanText(strip(NOISE.matcher(words).replaceAll(" "), " -"));
        return title.isEmpty() ? "Extra" : title;
    }

    /** Identity of a video at {@code path}, relative to the show's folder. */
    public static Identity identify(String show, String path) {
        String showName = cleanText(show);
        String filename = path.substring(path.lastIndexOf('/') + 1);
        int[] numbers = episodeNumbers(filename);
        if (numbers != null) {
            String label = String.format(Locale.ROOT, "%s S%02dE%02d", showName, numbers[0], numbers[1]);
            return new Identity(Kind.EPISODE, numbers[0], numbers[1], label);
        }
        Integer hint = seasonHint(path);
        String prefix = hint == null ? showName : String.format(Locale.ROOT, "%s S%02d", showName, hint);
        return new Identity(Kind.EXTRA, hint, null, cleanText(prefix + " - " + extraTitle(show, filename)));
    }

    /** Show and identity recovered from an existing label, e.g. from a file already on a player. */
    public static Map.Entry<String, Identity> identifyLabel(String label) {
        String clean = cleanText(label);
        Matcher numbered = LABEL_NUMBERED.matcher(clean);
        if (numbered.matches()) {
            Identity id = new Identity(Kind.EPISODE, Integer.parseInt(numbered.group(2)), Integer.parseInt(numbered.group(3)), clean);
            return new java.util.AbstractMap.SimpleImmutableEntry<>(numbered.group(1), id);
        }
        Matcher extra = LABEL_EXTRA.matcher(clean);
        if (extra.matches()) {
            Identity id = new Identity(Kind.EXTRA, Integer.parseInt(extra.group(2)), null, clean);
            return new java.util.AbstractMap.SimpleImmutableEntry<>(extra.group(1), id);
        }
        String show = clean.split(" - ", 2)[0];
        return new java.util.AbstractMap.SimpleImmutableEntry<>(show, new Identity(Kind.EXTRA, null, null, clean));
    }

    /** The name an episode has on the player's VIDEO folder. */
    public static String playerFileName(String label) {
        return label + PLAYER_SUFFIX;
    }

    // ---- planning --------------------------------------------------------------------

    public enum State { PENDING, STAGED, FAILED }

    /** One known source video, as the planner needs to see it. {@code bytes <= 0} means unknown. */
    public static final class Candidate {
        public final String key;
        public final String show;
        public final Identity identity;
        public final long bytes;
        public final State state;

        public Candidate(String key, String show, Identity identity, long bytes, State state) {
            this.key = key;
            this.show = show;
            this.identity = identity;
            this.bytes = bytes;
            this.state = state;
        }
    }

    /** Which shows a player may receive: an explicit list (case-insensitive) or every show. */
    public static final class Allowlist {
        private final Set<String> shows;
        private final boolean all;

        private Allowlist(Set<String> shows, boolean all) {
            this.shows = shows;
            this.all = all;
        }

        public static Allowlist all() {
            return new Allowlist(Collections.emptySet(), true);
        }

        public static Allowlist of(Collection<String> shows) {
            Set<String> folded = new HashSet<>();
            for (String show : shows) folded.add(show.toLowerCase(Locale.ROOT));
            return new Allowlist(folded, false);
        }

        public boolean allows(String show) {
            return all || shows.contains(show.toLowerCase(Locale.ROOT));
        }
    }

    public static final Comparator<Candidate> VIEWING_ORDER = Comparator
        .comparing((Candidate c) -> c.identity.season == null ? 999 : c.identity.season)
        .thenComparing(c -> c.identity.episode == null ? 9999 : c.identity.episode)
        .thenComparing(c -> c.identity.label);

    private static final Comparator<Candidate> SMALLEST_FIRST = Comparator
        .comparing((Candidate c) -> c.bytes > 0 ? c.bytes : Long.MAX_VALUE)
        .thenComparing(c -> c.identity.label);

    /**
     * Queueable videos per show in viewing order. Numbered episodes win; a show with no numbered
     * episode at all offers its extras. Duplicates and permanently failed files are left out,
     * so one broken file never stalls a show.
     */
    public static Map<String, List<Candidate>> byShow(Collection<Candidate> candidates) {
        Map<String, List<Candidate>> grouped = new TreeMap<>(String.CASE_INSENSITIVE_ORDER);
        for (Candidate c : candidates) {
            if (c.identity.kind != Kind.DUPLICATE && c.state != State.FAILED) {
                grouped.computeIfAbsent(c.show, k -> new ArrayList<>()).add(c);
            }
        }
        Map<String, List<Candidate>> result = new LinkedHashMap<>();
        for (Map.Entry<String, List<Candidate>> entry : grouped.entrySet()) {
            List<Candidate> numbered = new ArrayList<>();
            for (Candidate c : entry.getValue()) if (c.identity.kind == Kind.EPISODE) numbered.add(c);
            List<Candidate> chosen = new ArrayList<>(numbered.isEmpty() ? entry.getValue() : numbered);
            chosen.sort(VIEWING_ORDER);
            result.put(entry.getKey(), chosen);
        }
        return result;
    }

    /**
     * Up to {@code perShow} not-yet-had episodes of each allowed show, round-robin across shows,
     * smallest first within each round. {@code had} holds every key the player has had: copied,
     * found on it, or removed from it by hand (a removed episode is never pushed back).
     */
    public static List<Candidate> nextForPlayer(Map<String, List<Candidate>> shows, Set<String> had,
                                                Allowlist allowlist, int perShow) {
        List<List<Candidate>> perShowLists = new ArrayList<>();
        for (Map.Entry<String, List<Candidate>> entry : shows.entrySet()) {
            if (allowlist.allows(entry.getKey())) perShowLists.add(upcoming(entry.getValue(), had, perShow));
        }
        List<Candidate> ordered = new ArrayList<>();
        for (int rank = 0; rank < perShow; rank++) {
            List<Candidate> layer = new ArrayList<>();
            for (List<Candidate> list : perShowLists) if (rank < list.size()) layer.add(list.get(rank));
            layer.sort(SMALLEST_FIRST);
            ordered.addAll(layer);
        }
        return ordered;
    }

    private static List<Candidate> upcoming(List<Candidate> inOrder, Set<String> had, int perShow) {
        List<Candidate> next = new ArrayList<>();
        for (Candidate c : inOrder) {
            if (next.size() == perShow) break;
            if (!had.contains(c.key)) next.add(c);
        }
        return next;
    }

    // ---- reconciliation and staging ------------------------------------------------------

    /** What to do about a file found under an episode's player name before planning. */
    public enum Found { NOT_ON_PLAYER, HAD, REPLACE_TRUNCATED }

    /**
     * A file already on the player under this episode's name counts as had, whoever wrote it,
     * except a proven truncated prefix of our own staged file, which may be replaced.
     *
     * @param playerBytes size of the player file, or a negative number when there is none
     * @param stagedBytes size of our verified staged file, or a negative number when there is none
     * @param ownPrefix   checked only when the player file is shorter: is it a byte prefix of the staged file?
     */
    public static Found classifyPlayerFile(long playerBytes, long stagedBytes, BooleanSupplier ownPrefix) {
        if (playerBytes < 0) return Found.NOT_ON_PLAYER;
        if (stagedBytes > 0 && playerBytes < stagedBytes && ownPrefix.getAsBoolean()) return Found.REPLACE_TRUNCATED;
        return Found.HAD;
    }

    /** True when {@code candidate} is byte-for-byte the first {@code candidateBytes} of {@code source}. */
    public static boolean isOwnPrefix(InputStream source, InputStream candidate, long candidateBytes) throws IOException {
        byte[] a = new byte[64 * 1024];
        byte[] b = new byte[64 * 1024];
        long remaining = candidateBytes;
        while (remaining > 0) {
            int want = (int) Math.min(a.length, remaining);
            if (!readFully(source, a, want) || !readFully(candidate, b, want)) return false;
            if (!Arrays.equals(Arrays.copyOf(a, want), Arrays.copyOf(b, want))) return false;
            remaining -= want;
        }
        return true;
    }

    private static boolean readFully(InputStream in, byte[] buffer, int length) throws IOException {
        int offset = 0;
        while (offset < length) {
            int n = in.read(buffer, offset, length - offset);
            if (n < 0) return false;
            offset += n;
        }
        return true;
    }

    /**
     * A staged file is prepared once per source and may be released only when every player
     * that wants it has a verified copy, so a show allowed on two players is converted once.
     */
    public static boolean canReleaseStaged(Set<String> playersWantingIt, Set<String> playersWithVerifiedCopy) {
        return playersWithVerifiedCopy.containsAll(playersWantingIt);
    }
}
